def patch_font(font_path, mapping):
    tt = TTFont(font_path)
    existing_glyphs = set(tt.getGlyphOrder())
    count = 0
    for table in tt['cmap'].tables:
        if table.isUnicode():
            for gname, u in mapping.items():
                if gname in existing_glyphs:
                    table.cmap[u] = gname
                    count += 1
    tt.save(font_path)
    return count

def main():
    ttf_dir = 'css/bakoma/ttf'
    for f in os.listdir(ttf_dir):
        p = os.path.join(ttf_dir, f)
        if f.startswith('cmsy') or f.startswith('cmbsy'):
            c = patch_font(p, CMSY_GLYPH_TO_UNICODE)
            print(f'Patched {f} with {c} unicode mappings')
        elif f.startswith('cmmi') or f.startswith('cmmib'):
            c = patch_font(p, CMMI_GLYPH_TO_UNICODE)
            print(f'Patched {f} with {c} unicode mappings')

if __name__ == '__main__':
    main()
